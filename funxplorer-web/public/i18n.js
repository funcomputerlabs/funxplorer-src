I18N["es-MX"] = I18N.es;

function t(id) {
  return I18N[id] || I18N[id.split("-")[0]] || I18N.es;
}

function applyLang(id) {
  const pack = t(id);
  document.documentElement.lang = id;
  document.documentElement.dir = RTL.has(id.split("-")[0]) ? "rtl" : "ltr";
  document.title = pack.title;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) {
    desc.setAttribute("content", pack.description);
  }
  document.querySelectorAll("[data-i18n]").forEach(node => {
    const key = node.getAttribute("data-i18n");
    if (pack[key]) {
      node.textContent = pack[key];
    }
  });
  const select = document.getElementById("lang-select");
  if (select) {
    select.setAttribute("aria-label", pack.language);
    select.value = I18N[id] ? id : id.split("-")[0] in I18N ? id.split("-")[0] : "es";
  }
}
