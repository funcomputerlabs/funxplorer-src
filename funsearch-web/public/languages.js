function funsearchUi(id) {
  return FUNSEARCH_UI[id] || FUNSEARCH_UI[id.split("-")[0]] || FUNSEARCH_UI.es;
}

function resolveFunsearchLang(code) {
  const raw = (code || "es").trim();
  return (
    FUNSEARCH_LANGS.find(l => l.id.toLowerCase() === raw.toLowerCase()) ||
    FUNSEARCH_LANGS.find(l => raw.toLowerCase().startsWith(l.id.toLowerCase())) ||
    FUNSEARCH_LANGS.find(l => l.id === "es") ||
    FUNSEARCH_LANGS[0]
  );
}
